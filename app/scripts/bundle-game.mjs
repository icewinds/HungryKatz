// Packs the HungryKatz web game (the repo root) into one self-contained page for the app's WebView:
// the ES modules become one script (esbuild), the stylesheet is inlined with its fonts and images as data URIs,
// and the page tells the game it is running in the app. Writes game-html.js (default export: the page).
// Run after changing the game: npm run bundle-game (npm start / android / ios run it for you).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..'), out = path.resolve(here, '../game-html.js');
const MIME = { '.png': 'image/png', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' };
const dataUri = file => `data:${MIME[path.extname(file)]};base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`;

const js = (await build({ entryPoints: [path.join(root, 'js/game.js')], bundle: true, format: 'iife', target: 'es2020', minify: true, write: false }))
  .outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = (await build({ entryPoints: [path.join(root, 'css/styles.css')], bundle: true, minify: true, write: false,
  loader: { '.woff2': 'dataurl', '.svg': 'dataurl', '.png': 'dataurl' } })).outputFiles[0].text;

// In the app everything is inline, so the page's CSP allows inline code and data: assets (nothing is fetched).
const CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src data:; img-src data: blob:; media-src data: blob:; connect-src 'none'; base-uri 'none'; form-action 'none'";
const swap = (html, from, to) => { if (!from.test(html)) throw new Error(`bundle-game: index.html no longer matches ${from}`); return html.replace(from, to); };

let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = swap(html, /<meta http-equiv="Content-Security-Policy"[^>]*>/, `<meta http-equiv="Content-Security-Policy" content="${CSP}">`);
html = swap(html, /<link rel="manifest"[^>]*>\s*/, '');
html = swap(html, /<link rel="preload"[^>]*>\s*/, '');
html = html.replace(/<link rel="(icon|apple-touch-icon)"[^>]*>\s*/g, '');
html = swap(html, /<link rel="stylesheet" href="css\/styles\.css">/, () => `<style>${css}</style>`);
html = swap(html, /<script type="module" src="js\/game\.js"><\/script>/, () => `<script>window.hungryKatzApp = true;</script>\n<script>${js}</script>`);
html = html.replace(/(src|href)="(assets\/[^"]+\.(?:png|svg))"/g, (m, attr, file) => `${attr}="${dataUri(file)}"`);

fs.writeFileSync(out, `// Generated by scripts/bundle-game.mjs from the web game; do not edit by hand.\nexport default ${JSON.stringify(html)};\n`);
console.log(`bundle-game: wrote game-html.js (${Math.round(fs.statSync(out).size / 1024)} KB)`);
